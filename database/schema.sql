BEGIN;

CREATE TABLE IF NOT EXISTS roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(30) NOT NULL UNIQUE,
  descripcion VARCHAR(150),
  CONSTRAINT roles_nombre_check CHECK (nombre IN ('Administrador', 'Gerente', 'Cajero'))
);

CREATE TABLE IF NOT EXISTS usuarios (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre VARCHAR(80) NOT NULL,
  apellido VARCHAR(80) NOT NULL,
  username VARCHAR(40) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol_id INTEGER NOT NULL REFERENCES roles(id),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_por UUID REFERENCES usuarios(id),
  intentos_fallidos INTEGER NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
  bloqueado_hasta TIMESTAMP,
  ultimo_login TIMESTAMP,
  foto_url VARCHAR(255),
  debe_cambiar_password BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categorias (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL UNIQUE,
  descripcion VARCHAR(150),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS unidades_medida (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(30) NOT NULL UNIQUE,
  abreviatura VARCHAR(10) NOT NULL UNIQUE,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE unidades_medida
  ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS productos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo VARCHAR(30) NOT NULL UNIQUE,
  codigo_barras VARCHAR(50) UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  descripcion VARCHAR(255),
  categoria_id INTEGER NOT NULL REFERENCES categorias(id),
  unidad_id INTEGER NOT NULL REFERENCES unidades_medida(id),
  costo DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (costo >= 0),
  precio_final DECIMAL(12,2) NOT NULL CHECK (precio_final >= 0),
  tasa_itbis DECIMAL(5,2) NOT NULL DEFAULT 18.00 CHECK (tasa_itbis IN (0, 16, 18)),
  stock_minimo DECIMAL(12,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
  imagen_url VARCHAR(255),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS historial_precios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id UUID NOT NULL REFERENCES productos(id),
  costo_anterior DECIMAL(12,2) NOT NULL CHECK (costo_anterior >= 0),
  costo_nuevo DECIMAL(12,2) NOT NULL CHECK (costo_nuevo >= 0),
  precio_anterior DECIMAL(12,2) NOT NULL CHECK (precio_anterior >= 0),
  precio_nuevo DECIMAL(12,2) NOT NULL CHECK (precio_nuevo >= 0),
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS inventario (
  producto_id UUID PRIMARY KEY REFERENCES productos(id),
  cantidad_actual DECIMAL(12,3) NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS movimientos_inventario (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  producto_id UUID NOT NULL REFERENCES productos(id),
  tipo VARCHAR(30) NOT NULL CHECK (tipo IN (
    'ENTRADA_COMPRA',
    'SALIDA_VENTA',
    'DEVOLUCION_CLIENTE',
    'AJUSTE',
    'MERMA',
    'ANULACION_VENTA'
  )),
  cantidad DECIMAL(12,3) NOT NULL CHECK (cantidad <> 0),
  stock_resultante DECIMAL(12,3) NOT NULL,
  referencia_tipo VARCHAR(20) CHECK (referencia_tipo IN ('VENTA', 'COMPRA', 'DEVOLUCION')),
  referencia_id UUID,
  motivo VARCHAR(200),
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT movimientos_inventario_motivo_check CHECK (
    tipo NOT IN ('AJUSTE', 'MERMA') OR (motivo IS NOT NULL AND btrim(motivo) <> '')
  )
);

CREATE TABLE IF NOT EXISTS suplidores (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre VARCHAR(120) NOT NULL,
  rnc VARCHAR(15),
  contacto VARCHAR(80),
  telefono VARCHAR(20),
  email VARCHAR(100),
  direccion VARCHAR(200),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS compras (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  suplidor_id UUID NOT NULL REFERENCES suplidores(id),
  numero_factura_suplidor VARCHAR(40),
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  total DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  estado VARCHAR(15) NOT NULL DEFAULT 'COMPLETADA' CHECK (estado IN ('COMPLETADA', 'ANULADA')),
  observacion VARCHAR(255),
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS detalle_compras (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  compra_id UUID NOT NULL REFERENCES compras(id),
  producto_id UUID NOT NULL REFERENCES productos(id),
  cantidad DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
  costo_unitario DECIMAL(12,2) NOT NULL CHECK (costo_unitario >= 0),
  subtotal DECIMAL(12,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS cajas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS turnos_caja (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  caja_id INTEGER NOT NULL REFERENCES cajas(id),
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  fecha_apertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  efectivo_inicial DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (efectivo_inicial >= 0),
  fecha_cierre TIMESTAMP,
  efectivo_esperado DECIMAL(12,2),
  efectivo_contado DECIMAL(12,2) CHECK (efectivo_contado >= 0),
  diferencia DECIMAL(12,2),
  total_tarjeta DECIMAL(12,2) CHECK (total_tarjeta >= 0),
  total_transferencia DECIMAL(12,2) CHECK (total_transferencia >= 0),
  estado VARCHAR(10) NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'CERRADA')),
  observacion VARCHAR(255),
  CONSTRAINT turnos_caja_cierre_check CHECK (
    (estado = 'ABIERTA' AND fecha_cierre IS NULL)
    OR (estado = 'CERRADA' AND fecha_cierre IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS movimientos_caja (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno_id UUID NOT NULL REFERENCES turnos_caja(id),
  tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA')),
  monto DECIMAL(12,2) NOT NULL CHECK (monto > 0),
  motivo VARCHAR(200) NOT NULL,
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS metodos_pago (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(30) NOT NULL UNIQUE,
  es_efectivo BOOLEAN NOT NULL DEFAULT FALSE,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS ventas (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  numero_recibo VARCHAR(30) NOT NULL UNIQUE,
  turno_id UUID NOT NULL REFERENCES turnos_caja(id),
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  subtotal_base DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (subtotal_base >= 0),
  total_itbis DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total_itbis >= 0),
  total DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  estado VARCHAR(15) NOT NULL DEFAULT 'COMPLETADA' CHECK (estado IN ('COMPLETADA', 'ANULADA')),
  anulada_por UUID REFERENCES usuarios(id),
  fecha_anulacion TIMESTAMP,
  motivo_anulacion VARCHAR(200),
  CONSTRAINT ventas_totales_check CHECK (total = subtotal_base + total_itbis),
  CONSTRAINT ventas_anulacion_check CHECK (
    estado = 'COMPLETADA'
    OR (
      anulada_por IS NOT NULL
      AND fecha_anulacion IS NOT NULL
      AND motivo_anulacion IS NOT NULL
      AND btrim(motivo_anulacion) <> ''
    )
  )
);

CREATE TABLE IF NOT EXISTS detalle_ventas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id UUID NOT NULL REFERENCES ventas(id),
  producto_id UUID NOT NULL REFERENCES productos(id),
  nombre_producto VARCHAR(120) NOT NULL,
  cantidad DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
  precio_unitario DECIMAL(12,2) NOT NULL CHECK (precio_unitario >= 0),
  costo_unitario DECIMAL(12,2) NOT NULL CHECK (costo_unitario >= 0),
  tasa_itbis DECIMAL(5,2) NOT NULL CHECK (tasa_itbis IN (0, 16, 18)),
  base_linea DECIMAL(12,2) NOT NULL CHECK (base_linea >= 0),
  itbis_linea DECIMAL(12,2) NOT NULL CHECK (itbis_linea >= 0),
  total_linea DECIMAL(12,2) NOT NULL CHECK (total_linea >= 0),
  CONSTRAINT detalle_ventas_totales_check CHECK (total_linea = base_linea + itbis_linea)
);

CREATE TABLE IF NOT EXISTS pagos_venta (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id UUID NOT NULL REFERENCES ventas(id),
  metodo_pago_id INTEGER NOT NULL REFERENCES metodos_pago(id),
  monto DECIMAL(12,2) NOT NULL CHECK (monto > 0),
  monto_recibido DECIMAL(12,2) CHECK (monto_recibido >= 0),
  cambio DECIMAL(12,2) CHECK (cambio >= 0),
  referencia VARCHAR(50),
  CONSTRAINT pagos_venta_recibido_check CHECK (monto_recibido IS NULL OR monto_recibido >= monto),
  CONSTRAINT pagos_venta_cambio_calculo_check CHECK (
    cambio IS NULL
    OR (monto_recibido IS NOT NULL AND cambio = monto_recibido - monto)
  )
);

CREATE TABLE IF NOT EXISTS devoluciones (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venta_id UUID NOT NULL REFERENCES ventas(id),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  motivo VARCHAR(200) NOT NULL CHECK (btrim(motivo) <> ''),
  total_devuelto DECIMAL(12,2) NOT NULL CHECK (total_devuelto >= 0),
  tipo_reembolso VARCHAR(20) NOT NULL CHECK (tipo_reembolso IN ('EFECTIVO', 'CAMBIO')),
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  autorizado_por UUID REFERENCES usuarios(id)
);

CREATE TABLE IF NOT EXISTS detalle_devoluciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  devolucion_id UUID NOT NULL REFERENCES devoluciones(id),
  detalle_venta_id BIGINT NOT NULL REFERENCES detalle_ventas(id),
  producto_id UUID NOT NULL REFERENCES productos(id),
  cantidad DECIMAL(12,3) NOT NULL CHECK (cantidad > 0),
  monto DECIMAL(12,2) NOT NULL CHECK (monto >= 0),
  reingresa_inventario BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS categorias_gasto (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gastos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  categoria_gasto_id INTEGER NOT NULL REFERENCES categorias_gasto(id),
  descripcion VARCHAR(200) NOT NULL,
  monto DECIMAL(12,2) NOT NULL CHECK (monto > 0),
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  usuario_id UUID NOT NULL REFERENCES usuarios(id),
  turno_id UUID REFERENCES turnos_caja(id)
);

CREATE TABLE IF NOT EXISTS configuracion (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  nombre_negocio VARCHAR(120) NOT NULL,
  rnc VARCHAR(15),
  direccion VARCHAR(200),
  telefono VARCHAR(20),
  logo_url VARCHAR(255),
  tasa_itbis DECIMAL(5,2) NOT NULL DEFAULT 18.00 CHECK (tasa_itbis IN (0, 16, 18)),
  moneda VARCHAR(5) NOT NULL DEFAULT 'DOP',
  prefijo_recibo VARCHAR(5) DEFAULT 'R',
  leyenda_recibo VARCHAR(255) NOT NULL DEFAULT 'Recibo interno, no válido como comprobante fiscal'
);

CREATE TABLE IF NOT EXISTS copias_seguridad (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre_archivo VARCHAR(150) NOT NULL,
  ubicacion VARCHAR(255) NOT NULL,
  tamano_bytes BIGINT CHECK (tamano_bytes >= 0),
  tipo VARCHAR(12) NOT NULL CHECK (tipo IN ('MANUAL', 'AUTOMATICA')),
  estado VARCHAR(12) NOT NULL CHECK (estado IN ('EXITOSA', 'FALLIDA')),
  usuario_id UUID REFERENCES usuarios(id),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notas VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id UUID REFERENCES usuarios(id),
  accion VARCHAR(40) NOT NULL,
  entidad VARCHAR(40),
  entidad_id VARCHAR(40),
  datos_anteriores JSON,
  datos_nuevos JSON,
  ip VARCHAR(45),
  fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS kora_ai_conocimiento (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tema VARCHAR(80) NOT NULL,
  palabras_clave VARCHAR(255) NOT NULL,
  pregunta VARCHAR(255) NOT NULL,
  respuesta TEXT NOT NULL,
  roles_permitidos VARCHAR(100) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS turnos_caja_abierta_por_caja
  ON turnos_caja (caja_id)
  WHERE estado = 'ABIERTA';

CREATE UNIQUE INDEX IF NOT EXISTS turnos_caja_abierta_por_usuario
  ON turnos_caja (usuario_id)
  WHERE estado = 'ABIERTA';

CREATE INDEX IF NOT EXISTS usuarios_rol_idx ON usuarios (rol_id);
CREATE INDEX IF NOT EXISTS productos_categoria_idx ON productos (categoria_id);
CREATE INDEX IF NOT EXISTS productos_unidad_idx ON productos (unidad_id);
CREATE INDEX IF NOT EXISTS productos_nombre_idx ON productos (nombre);
CREATE INDEX IF NOT EXISTS historial_precios_producto_idx ON historial_precios (producto_id, fecha);
CREATE INDEX IF NOT EXISTS movimientos_inventario_producto_idx ON movimientos_inventario (producto_id, created_at);
CREATE INDEX IF NOT EXISTS movimientos_inventario_referencia_idx ON movimientos_inventario (referencia_tipo, referencia_id);
CREATE INDEX IF NOT EXISTS compras_suplidor_idx ON compras (suplidor_id);
CREATE INDEX IF NOT EXISTS compras_fecha_idx ON compras (fecha);
CREATE INDEX IF NOT EXISTS detalle_compras_compra_idx ON detalle_compras (compra_id);
CREATE INDEX IF NOT EXISTS detalle_compras_producto_idx ON detalle_compras (producto_id);
CREATE INDEX IF NOT EXISTS turnos_caja_caja_idx ON turnos_caja (caja_id);
CREATE INDEX IF NOT EXISTS turnos_caja_usuario_idx ON turnos_caja (usuario_id);
CREATE INDEX IF NOT EXISTS turnos_caja_fecha_idx ON turnos_caja (fecha_apertura);
CREATE INDEX IF NOT EXISTS movimientos_caja_turno_idx ON movimientos_caja (turno_id);
CREATE INDEX IF NOT EXISTS ventas_turno_idx ON ventas (turno_id);
CREATE INDEX IF NOT EXISTS ventas_usuario_idx ON ventas (usuario_id);
CREATE INDEX IF NOT EXISTS ventas_fecha_idx ON ventas (fecha_hora);
CREATE INDEX IF NOT EXISTS detalle_ventas_venta_idx ON detalle_ventas (venta_id);
CREATE INDEX IF NOT EXISTS detalle_ventas_producto_idx ON detalle_ventas (producto_id);
CREATE INDEX IF NOT EXISTS pagos_venta_venta_idx ON pagos_venta (venta_id);
CREATE INDEX IF NOT EXISTS devoluciones_venta_idx ON devoluciones (venta_id);
CREATE INDEX IF NOT EXISTS detalle_devoluciones_devolucion_idx ON detalle_devoluciones (devolucion_id);
CREATE INDEX IF NOT EXISTS gastos_fecha_idx ON gastos (fecha);
CREATE INDEX IF NOT EXISTS gastos_categoria_idx ON gastos (categoria_gasto_id);
CREATE INDEX IF NOT EXISTS auditoria_usuario_idx ON auditoria (usuario_id, fecha);
CREATE INDEX IF NOT EXISTS auditoria_entidad_idx ON auditoria (entidad, entidad_id);

CREATE OR REPLACE FUNCTION actualizar_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS usuarios_updated_at ON usuarios;
CREATE TRIGGER usuarios_updated_at
BEFORE UPDATE ON usuarios
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();

DROP TRIGGER IF EXISTS productos_updated_at ON productos;
CREATE TRIGGER productos_updated_at
BEFORE UPDATE ON productos
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();

DROP TRIGGER IF EXISTS inventario_updated_at ON inventario;
CREATE TRIGGER inventario_updated_at
BEFORE UPDATE ON inventario
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();

COMMIT;
