export function obtenerComponenteIcono(nombre, fallback = Tag) {
  if (!nombre) return fallback;
  return MAPA_ICONOS[nombre] || fallback;
}

export function renderIcono(nombre, props = {}, fallback = Tag) {
  const Componente = obtenerComponenteIcono(nombre, fallback);
  return <Componente {...props} />;
}
